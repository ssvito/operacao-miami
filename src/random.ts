/**
 * Tiny seeded PRNG (mulberry32). Phases use a fixed seed so a run is the same every time:
 * learnable for the player, reproducible for a headless simulation.
 */
export function rng(seed: number): () => number {
  let a = seed;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
